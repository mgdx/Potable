#!/usr/bin/env python3
"""Generate the adaptive launcher icon VectorDrawables from the logo SVG.

Usage (from the repository root):

    python3 tools/brand/generate_vectors.py [--check-only]

Reads docs/brand/potable_logo.svg (108 x 108 grid, see SPEC §18) and writes
into app/src/main/res/drawable/:

- ic_launcher_background.xml  flat #2350B5 (the full-size <rect> of the SVG);
- ic_launcher_foreground.xml  faucet and drop in white, curve as a #2350B5
                              stroke (round caps and joins), 108 x 108 dp;
- ic_launcher_monochrome.xml  faucet and drop silhouette with the curve
                              hollowed out: the stroke is converted into its
                              outline (stroke_outline.py) and subtracted from
                              the drop with fillType="evenOdd".

It then checks, by rasterising with pycairo, that:

- the outline matches the stroke it replaces (pixel comparison);
- the outline lies entirely inside the drop (otherwise evenOdd would add
  ink instead of removing it);
- the whole motif fits in the 66-unit safe zone (square 21..87, and the
  66-unit circle centred on 54,54 used by Android's documentation).

Requirements: Python 3.10+, pycairo (python3-cairo), numpy.
"""

from __future__ import annotations

import argparse
import math
import os
import sys

import cairo
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stroke_outline  # noqa: E402
import svgsubset  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SVG = os.path.join(ROOT, "docs", "brand", "potable_logo.svg")
DRAWABLE = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

HEADER = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/brand/generate_vectors.py from docs/brand/potable_logo.svg. Do not edit by hand. -->\n"


def color(value: str) -> str:
    value = value.upper()
    if value in ("WHITE",):
        return "#FFFFFF"
    if not value.startswith("#") or len(value) not in (4, 7):
        raise ValueError(f"unsupported colour {value!r}")
    if len(value) == 4:
        value = "#" + "".join(ch * 2 for ch in value[1:])
    return value


def split(logo: svgsubset.Logo):
    """Return (background shape, foreground fills, strokes)."""
    _, _, w, h = logo.view_box
    background = None
    fills, strokes = [], []
    for s in logo.shapes:
        xs = [c[-2] for c in s.commands if c[0] != "Z"]
        ys = [c[-1] for c in s.commands if c[0] != "Z"]
        full = s.kind == "rect" and min(xs) <= 0 and min(ys) <= 0 and max(xs) >= w and max(ys) >= h
        if full and background is None:
            background = s
        elif s.stroke:
            if s.kind != "polyline" or s.paint.get("stroke-linecap") != "round" or s.paint.get("stroke-linejoin") != "round":
                raise ValueError("only round-capped, round-joined polylines can be stroked")
            strokes.append(s)
        else:
            fills.append(s)
    if background is None:
        raise ValueError("the SVG has no full-size background <rect>")
    return background, fills, strokes


def vector(paths: list[str], w: float, h: float) -> str:
    body = "\n".join(paths)
    return (
        HEADER
        + "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
        + f"    android:width=\"{svgsubset.fmt(w)}dp\"\n"
        + f"    android:height=\"{svgsubset.fmt(h)}dp\"\n"
        + f"    android:viewportWidth=\"{svgsubset.fmt(w)}\"\n"
        + f"    android:viewportHeight=\"{svgsubset.fmt(h)}\">\n"
        + body
        + "\n</vector>\n"
    )


def fill_path(data: str, fill: str, even_odd: bool = False) -> str:
    rule = "\n        android:fillType=\"evenOdd\"" if even_odd else ""
    return f"    <path\n        android:fillColor=\"{fill}\"{rule}\n        android:pathData=\"{data}\" />"


def stroke_path(s: svgsubset.Shape) -> str:
    return (
        "    <path\n"
        + f"        android:strokeColor=\"{color(s.stroke)}\"\n"
        + f"        android:strokeWidth=\"{svgsubset.fmt(s.stroke_width)}\"\n"
        + "        android:strokeLineCap=\"round\"\n"
        + "        android:strokeLineJoin=\"round\"\n"
        + f"        android:pathData=\"{svgsubset.to_path_data(s.commands)}\" />"
    )


def drop_index(fills, stroke) -> int:
    """Index of the filled shape containing the stroke's first point."""
    for k, s in enumerate(fills):
        surf, ctx = _canvas(108, 1)
        svgsubset.cairo_path(ctx, s.commands)
        if ctx.in_fill(*stroke.points[0]):
            return k
    raise ValueError("the stroke is not drawn over any filled shape")


# --- rasterised checks -------------------------------------------------------

SCALE = 10


def _canvas(size, scale):
    surf = cairo.ImageSurface(cairo.FORMAT_A8, int(size * scale), int(size * scale))
    ctx = cairo.Context(surf)
    ctx.scale(scale, scale)
    return surf, ctx


def _mask(surf) -> np.ndarray:
    surf.flush()
    stride = surf.get_stride()
    data = np.frombuffer(surf.get_data(), dtype=np.uint8).reshape(surf.get_height(), stride)
    return data[:, : surf.get_width()] > 127


def raster_fill(commands, size=108):
    surf, ctx = _canvas(size, SCALE)
    svgsubset.cairo_path(ctx, commands)
    ctx.fill()
    return _mask(surf)


def raster_stroke(shape, size=108):
    surf, ctx = _canvas(size, SCALE)
    svgsubset.cairo_path(ctx, shape.commands)
    ctx.set_line_width(shape.stroke_width)
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    ctx.set_line_join(cairo.LINE_JOIN_ROUND)
    ctx.stroke()
    return _mask(surf)


def checks(fills, strokes, outlines, drop) -> bool:
    ok = True
    for s, o in zip(strokes, outlines):
        a, b = raster_stroke(s), raster_fill(o)
        diff = np.count_nonzero(a ^ b)
        print(f"outline vs stroke: {diff} differing pixels out of {np.count_nonzero(a)} (scale x{SCALE})")
        if diff > 0.01 * np.count_nonzero(a):
            ok = False
            print("  ERROR: the outline does not match the stroke")
        outside = np.count_nonzero(b & ~raster_fill(fills[drop].commands))
        print(f"outline pixels outside the drop: {outside}")
        if outside:
            ok = False
            print("  ERROR: the curve leaves the drop, evenOdd would not hollow it")

    ink = np.zeros((108 * SCALE, 108 * SCALE), dtype=bool)
    for s in fills:
        ink |= raster_fill(s.commands)
    ys, xs = np.nonzero(ink)
    x0, x1 = xs.min() / SCALE, (xs.max() + 1) / SCALE
    y0, y1 = ys.min() / SCALE, (ys.max() + 1) / SCALE
    print(f"motif bounding box: x {x0:.1f}..{x1:.1f}, y {y0:.1f}..{y1:.1f}")
    inside_square = x0 >= 21 and y0 >= 21 and x1 <= 87 and y1 <= 87
    print(f"inside the 21..87 safe square: {'yes' if inside_square else 'NO'}")
    ok &= inside_square
    cx = cy = 54 * SCALE
    radius = math.sqrt(((xs + 0.5 - cx) ** 2 + (ys + 0.5 - cy) ** 2).max()) / SCALE
    print(f"farthest ink from the centre: {radius:.2f} units (safe circle 33, visible circle 36)")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check-only", action="store_true", help="run the checks without writing files")
    args = parser.parse_args()

    logo = svgsubset.load(SVG)
    _, _, w, h = logo.view_box
    background, fills, strokes = split(logo)
    outlines = [stroke_outline.outline(s.points, s.stroke_width) for s in strokes]
    drop = drop_index(fills, strokes[0])

    ok = checks(fills, strokes, outlines, drop)
    if not ok:
        print("checks failed, nothing written", file=sys.stderr)
        return 1
    if args.check_only:
        return 0

    bg = vector([fill_path(svgsubset.to_path_data(background.commands), color(background.fill))], w, h)

    fg_paths = [fill_path(svgsubset.to_path_data(s.commands), color(s.fill)) for s in fills]
    fg_paths += [stroke_path(s) for s in strokes]
    fg = vector(fg_paths, w, h)

    mono_paths = []
    for k, s in enumerate(fills):
        data = svgsubset.to_path_data(s.commands)
        if k == drop:
            data += " " + " ".join(svgsubset.to_path_data(o) for o in outlines)
            mono_paths.append(fill_path(data, "#FFFFFF", even_odd=True))
        else:
            mono_paths.append(fill_path(data, "#FFFFFF"))
    mono = vector(mono_paths, w, h)

    for name, content in (
        ("ic_launcher_background.xml", bg),
        ("ic_launcher_foreground.xml", fg),
        ("ic_launcher_monochrome.xml", mono),
    ):
        path = os.path.join(DRAWABLE, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
